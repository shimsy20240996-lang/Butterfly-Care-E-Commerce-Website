export function filterFallbackProducts(params?: Record<string, any>): { products: Product[]; total: number } {
  let list = [...FALLBACK_PRODUCTS];

  if (params?.gender && params.gender !== 'all') {
    const g = params.gender.toLowerCase();
    if (g === 'boy') {
      list = list.filter(
        (p) =>
          p.gender === 'boy' ||
          p.gender === 'unisex' ||
          p.name.toLowerCase().includes('boy') ||
          p.categorySlug === 'clothing' ||
          p.categorySlug === 'bath-care'
      );
    } else if (g === 'girl') {
      list = list.filter(
        (p) =>
          p.gender === 'girl' ||
          p.gender === 'unisex' ||
          p.name.toLowerCase().includes('girl') ||
          p.categorySlug === 'clothing' ||
          p.categorySlug === 'toys-gifts'
      );
    } else if (g === 'mom') {
      list = list.filter((p) => p.gender === 'mom' || p.categorySlug === 'mom-care');
    } else {
      list = list.filter((p) => p.gender === g || p.gender === 'unisex');
    }
  }

  if (params?.category && params.category !== 'all') {
    const c = params.category.toLowerCase();
    list = list.filter((p) => p.categorySlug?.toLowerCase() === c || p.category === c);
  }

  if (params?.search && params.search.trim()) {
    const q = params.search.toLowerCase().trim();
    list = list.filter(
      (p) =>
        p.name.toLowerCase().includes(q) ||
        p.description.toLowerCase().includes(q) ||
        p.shortDescription.toLowerCase().includes(q) ||
        p.categoryName?.toLowerCase().includes(q)
    );
  }

  const limit = Number(params?.limit) || list.length;
  return {
    products: list.slice(0, limit),
    total: list.length,
  };
}
